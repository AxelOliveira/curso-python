"""""
Aula 10 - Convenções de nomes em Python

Em programação, existem padrões de nomenclatura que ajudam a manter o código organizado, legível e padronizado. Esses padrões são amplamente utilizados na comunidade e possuem nomes específicos.

Os principais padrões são:

🔹 PascalCase
Todas as palavras começam com letra maiúscula e não há separação entre elas.

Exemplos:
- MinhaClasse
- CarroEsportivo
- SistemaDeCadastro

👉 Em Python, esse padrão é utilizado para nomes de CLASSES.

---

🔹 camelCase
A primeira palavra começa com letra minúscula e as próximas iniciam com letra maiúscula.

Exemplos:
- minhaFuncao
- calcularMedia
- nomeDoUsuario

👉 Esse padrão NÃO é utilizado em Python (é comum em outras linguagens, como JavaScript).

---

🔹 snake_case
Todas as letras são minúsculas e as palavras são separadas pro underline(_).

Exemplos:
- minha_variavel
- funcao_legal
- calcular_media

👉 Esse é o padrão mais utilizado em Python para:
- variáveis
- funções
- métodos
- arquivos

---

📌 Resumo geral:

- Classes -> PascalCase
- Todo o restante -> snake_case

Seguir essas convenções facilita a leitura do código e mantém um padrão profissional utilizado pela comunidade Python.
"""